"""Split Meteocons monochrome SVGs into animatable layers (sun/moon, clouds, knock-out, precipitation, bolt).

Qt SVG ignores SMIL animation and <mask>, so layers are animated in QML and the
mask is replaced by a shell-coloured silhouette (knock-out).

Usage: gen-weather-icons.py <path to @meteocons/svg-static/package/monochrome> contents/ui/weather/icons
"""
import xml.etree.ElementTree as ET, json, os, re, sys
SRC=sys.argv[1]  # <meteocons>/monochrome from the MIT-licensed npm package @meteocons/svg-static
OUT=sys.argv[2]  # contents/ui/weather/icons
INK='#D1D3D8'; BG='#030304'
STROKE_SCALE=1.7  # existing strokes grow by 70%
FILL_OUTLINE=1.7   # filled outline shapes get a 1.7-unit round stroke (about +70% on 4-unit lines)
SVG='http://www.w3.org/2000/svg'
ET.register_namespace('',SVG)
ns='{%s}'%SVG
icons=['clear-day','clear-night','partly-cloudy-day','partly-cloudy-night','overcast','fog','drizzle','rain','sleet','snow','thunderstorms-rain','partly-cloudy-day-rain','partly-cloudy-night-rain','partly-cloudy-day-snow','partly-cloudy-night-snow','not-available']
def tag(e): return e.tag.replace(ns,'')
def find(e,i):
    for x in e.iter():
        if x.get('id')==i: return x
def ink(s): return s.replace('currentColor',INK)
def embolden(e):
    # Meteocons monochrome draws most lines as filled outlines; thicken those with a round stroke
    # and scale real strokes, keeping round caps/joins everywhere.
    for x in e.iter():
        if x.get('fill')=='currentColor':
            x.set('stroke','currentColor'); x.set('stroke-width',str(FILL_OUTLINE))
            x.set('stroke-linejoin','round'); x.set('stroke-linecap','round')
        elif x.get('stroke')=='currentColor':
            x.set('stroke-width',str(round(float(x.get('stroke-width','1'))*STROKE_SCALE,3)))
            x.set('stroke-linejoin','round'); x.set('stroke-linecap','round')
    return e
def wrap(children_xml):
    return '<svg viewBox="0 0 128 128" fill="none" xmlns="%s">%s</svg>\n'%(SVG,children_xml)
def ser(e):
    embolden(e)
    s=ET.tostring(e,encoding='unicode')
    s=re.sub(r' xmlns(:\w+)?="[^"]+"','',s)
    s=re.sub(r' id="[^"]*"','',s)
    return ink(s)
os.makedirs(OUT,exist_ok=True)
man={}
for name in icons:
    r=ET.parse(f'{SRC}/{name}.svg').getroot()
    m={}
    def w(suffix,xml):
        fn=f'{name}-{suffix}.svg'; open(f'{OUT}/{fn}','w').write(wrap(xml)); return fn
    sun=find(r,'Sun'); moon=find(r,'Moon')
    if sun is not None:
        core=find(sun,'Core')
        m['sun']=w('sun',ser(sun)); m['pivot']=[float(core.get('cx')),float(core.get('cy'))]
    elif moon is not None:
        m['moon']=w('moon',ser(moon))
    cl=find(r,'Clouds')
    if cl is not None:
        m['clouds']=w('clouds',ser(cl))
        sub=find(r,'Subtract')
        if sub is not None and (sun is not None or moon is not None):
            d=sub.get('d'); d=re.sub(r'^M128 0H0V128H128V0Z','',d)
            m['knock']=w('knock',f'<path d="{d}" fill="{BG}"/>')
    prec=find(r,'Precipitation')
    if prec is not None:
        drops=[]
        groups=[(g,k) for gid,k in (('Raindrops','rain'),('Snowflakes','snow')) for g in [find(prec,gid)] if g is not None]
        if not groups: groups=[(prec,'fog')]
        for g,k in groups:
            for c in g:
                if tag(c) in('path','g','circle','rect','line'):
                    drops.append({'f':w(f'd{len(drops)}',ser(c)),'k':k})
        m['drops']=drops
    if name=='clear-night':
        # Three four-point sparkles (large, medium, small) at the moon's upper right, one layer each.
        def sparkle(cx,cy,r):
            k=r*0.16
            d=(f'M{cx} {cy-r} Q{cx+k} {cy-k} {cx+r} {cy} Q{cx+k} {cy+k} {cx} {cy+r} '
               f'Q{cx-k} {cy+k} {cx-r} {cy} Q{cx-k} {cy-k} {cx} {cy-r}Z')
            return ET.fromstring(f'<path xmlns="{SVG}" d="{d}" fill="currentColor"/>')
        m['stars']=[{'f':w(f's{i}',ser(sparkle(cx,cy,r))),'cx':cx,'cy':cy} for i,(cx,cy,r) in enumerate([(94,46,14),(113,24,9),(84,20,6)])]
    bolt=find(r,'Lightning')
    if bolt is not None: m['bolt']=w('bolt',ser(bolt))
    # whole-icon fallback for no-layer icons
    if not m: m['whole']=w('all',ser(r.find(ns+'g')))
    man[name]=m
    print(name,list(m))
open(f'{OUT}/../WeatherManifest.js','w').write('.pragma library\n\n// Generated by scripts/gen-weather-icons.py from Meteocons (MIT). Do not edit.\nvar manifest = '+json.dumps(man,indent=1)+';\n')
