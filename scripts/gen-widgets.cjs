#!/usr/bin/env node
// Builds contents/ui/widgets/Manifests.js, the JS mirror of every widgets/<id>/manifest.json (QML cannot list a directory
// or read a file at run time, D-54). The JSON is the source of truth; never edit the mirror by hand.
//   scripts/gen-widgets.cjs           rewrite the mirror
//   scripts/gen-widgets.cjs --check   fail (exit 1) when the mirror does not match the manifests (CI, via tests/widget-manifests.test.cjs)
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..', 'contents', 'ui', 'widgets');
const out = path.join(root, 'Manifests.js');

function render() {
    const ids = fs.readdirSync(root, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
    const entries = ids.filter((id) => fs.existsSync(path.join(root, id, 'manifest.json'))).map((id) => {
        const manifest = JSON.parse(fs.readFileSync(path.join(root, id, 'manifest.json'), 'utf8'));
        return { id, manifest };
    });
    return '.pragma library\n\n// GENERATED by scripts/gen-widgets.cjs from widgets/<id>/manifest.json. Do not edit; CI fails on drift.\n\nconst list = '
        + JSON.stringify(entries, null, 4) + ';\n';
}

if (require.main === module) {
    const want = render();
    if (process.argv[2] === '--check') {
        const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
        if (have !== want) {
            console.error('contents/ui/widgets/Manifests.js does not match the manifests: run scripts/gen-widgets.cjs and commit the result');
            process.exit(1);
        }
        console.log('widgets: the manifest mirror matches');
    } else {
        fs.writeFileSync(out, want);
        console.log('wrote ' + path.relative(process.cwd(), out));
    }
}
module.exports = { render };
